import os
import subprocess

from .classifier import AUTOMATA
from .patterns import PATTERNS, pattern_alphabet

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")
DIAGRAMS = os.path.join(DOCS, "diagrams")


def state_number(name):
    return int(name[1:])


def edges(automaton):
    grouped = {}
    for state, moves in automaton.to_dict().items():
        for symbol, target in moves.items():
            grouped.setdefault((state.value, target.value), []).append(symbol.value)
    return dict(sorted(grouped.items(), key=lambda e: (state_number(e[0][0]), state_number(e[0][1]))))


def to_dot(profile, automaton):
    lines = [
        "digraph G {",
        f'  label="{profile}"; labelloc=t; fontname="Helvetica"; fontsize=16; rankdir=LR;',
        '  node [shape=circle, fontname="Helvetica"]; edge [fontname="Helvetica"];',
        "  __start [shape=point, width=0.1]; __start -> q0;",
    ]
    for state in sorted((s.value for s in automaton.states), key=state_number):
        final = any(f.value == state for f in automaton.final_states)
        lines.append(f"  {state} [shape={'doublecircle' if final else 'circle'}];")
    for (source, target), qualifications in edges(automaton).items():
        label = "\\n".join(qualifications)
        lines.append(f'  {source} -> {target} [label="{label}"];')
    lines.append("}")
    return "\n".join(lines)


def render(profile, automaton):
    dot_path = os.path.join(DIAGRAMS, f"automaton_{profile}.dot")
    with open(dot_path, "w", encoding="utf-8") as handle:
        handle.write(to_dot(profile, automaton))
    try:
        for fmt, extra in (("svg", []), ("png", ["-Gdpi=130"])):
            target = os.path.join(DIAGRAMS, f"automaton_{profile}.{fmt}")
            subprocess.run(["dot", f"-T{fmt}", *extra, dot_path, "-o", target], check=True)
    finally:
        os.remove(dot_path)


def section(profile, steps, automaton):
    states = sorted((s.value for s in automaton.states), key=state_number)
    finals = sorted((s.value for s in automaton.final_states), key=state_number)
    alphabet = pattern_alphabet(steps)
    lines = [
        f"## {profile}",
        "",
        "M = (Q, Σ, δ, q0, F)",
        "",
        f"- **Q** ({len(states)} states) = {{{', '.join(states)}}}",
        f"- **Σ** ({len(alphabet)} symbols) = {{{', '.join(alphabet)}}}",
        "- **q0** = q0",
        f"- **F** = {{{', '.join(finals)}}}",
        "",
        "| State | Input | δ (next state) |",
        "|-------|-------|----------------|",
    ]
    for (source, target), qualifications in edges(automaton).items():
        lines.append(f"| {source} | {', '.join(qualifications)} | {target} |")
    lines += [
        "",
        f"**Type:** DFA (`is_deterministic()` = {automaton.is_deterministic()}): no ε-transitions and at most one "
        "next state per (state, input). Missing transitions reject.",
        "",
        "**Pattern represented:**",
        "",
        "| Step | Qualifications | Required | Effect |",
        "|------|----------------|----------|--------|",
    ]
    count = 0
    for name, qualifications, required in steps:
        if required:
            count += 1
            effect = f"q{count - 1} → q{count}"
        else:
            effect = f"stays in q{count}"
        lines.append(f"| {name} | {', '.join(qualifications)} | {'yes' if required else 'no'} | {effect} |")
    lines += ["", f"![{profile}](diagrams/automaton_{profile}.svg)", ""]
    return lines


def main():
    os.makedirs(DIAGRAMS, exist_ok=True)
    lines = [
        "# Stage 3 — Formalization of the automata",
        "",
        "> Generated by `python -m Automata.formalization`. Do not edit by hand.",
        "",
        "Every automaton is a DFA M = (Q, Σ, δ, q0, F). In each table, a missing (state, input) pair rejects.",
        "",
    ]
    for profile, steps in PATTERNS.items():
        render(profile, AUTOMATA[profile])
        lines += section(profile, steps, AUTOMATA[profile])
    with open(os.path.join(DOCS, "stage3_formalization.md"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print(f"{len(AUTOMATA)} automata documented.")


if __name__ == "__main__":
    main()
