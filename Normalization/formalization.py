import os
from collections import defaultdict

from .builder import build_qualification_specs, build_union_spec
from .catalog import CATALOG, END_MARKER

OUTPUT_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "docs",
    "stage2_formalization.md",
)


def display_symbol(symbol):
    return "␣" if symbol == " " else symbol


def state_order(state):
    return int(state[1:])


def sorted_states(states):
    return sorted(states, key=state_order)


def collapsed_edges(spec):
    """Group edges by (source, target, output) merging letter cases.

    Returns a list of (source, "r|R", target, output_text) sorted by state.
    """
    groups = defaultdict(list)
    for (source, symbol), target in spec.delta.items():
        groups[(source, target, spec.omega[(source, symbol)])].append(symbol)
    edges = []
    for (source, target, output), symbols in groups.items():
        label = "|".join(display_symbol(s) for s in sorted(symbols, key=lambda s: (s.lower(), s.isupper())))
        edges.append((source, label, target, "".join(output) if output else "ε"))
    return sorted(edges, key=lambda e: (state_order(e[0]), e[1]))


def _set_text(items):
    return "{" + ", ".join(items) + "}"


def _states_text(states):
    ordered = sorted_states(states)
    if len(ordered) > 40:
        return f"{{{ordered[0]}, {ordered[1]}, ..., {ordered[-1]}}}"
    return _set_text(ordered)


def formal_definition_md(spec, full_tables=True, heading_level=3):
    """Markdown with the 7-tuple of one transducer."""
    hashes = "#" * heading_level
    inputs = sorted(spec.input_alphabet, key=lambda s: (s.lower(), s.isupper()))
    outputs = sorted(spec.output_alphabet)
    lines = [
        f"{hashes} {spec.name}",
        "",
        "M = (Q, Σ, Γ, δ, ω, q0, F)",
        "",
        f"- **Q** ({len(spec.states)} states) = "
        + _states_text(spec.states),
        f"- **Σ** ({len(inputs)} symbols) = "
        + _set_text(display_symbol(s) for s in inputs),
        f"- **Γ** = {_set_text(outputs)}",
        f"- **q0** = {spec.start}",
        f"- **F** = {_set_text(sorted_states(spec.finals))}",
        f"- **δ, ω**: {len(spec.delta)} transitions "
        f"({len(collapsed_edges(spec))} rows after merging letter cases)",
        "",
    ]
    if full_tables:
        lines += [
            "| State | Input | δ (next state) | ω (output) |",
            "|-------|-------|----------------|------------|",
        ]
        for source, label, target, output in collapsed_edges(spec):
            lines.append(f"| {source} | {label} | {target} | {output} |")
        lines.append("")
    return "\n".join(lines)


def generate_document(catalog=None):
    catalog = CATALOG if catalog is None else catalog
    union = build_union_spec(catalog)
    parts = [
        "# Stage 2 — Formalization of the transducers",
        "",
        "> Generated by `python -m normalization.formalization`. Do not edit by hand.",
        "",
        "## Conventions",
        "",
        "- Transducers are deterministic finite-state transducers of Mealy type: "
        "the output is attached to each transition (ω: Q × Σ → Γ*).",
        f"- Every token is read followed by the end marker `{END_MARKER}`. "
        "Reading it from the state of a complete variant goes to the accepting "
        "state and emits the canonical name (a single symbol of Γ). "
        "Every other transition outputs ε.",
        "- Letters are accepted in lower and upper case (Σ contains both). "
        "The tables merge the two cases into one row (`r|R`).",
        "- A token is **accepted** (normalized) only if the machine ends in F; "
        "otherwise it is rejected and reported as unrecognized.",
        "- `␣` stands for the space character.",
        "",
        "## Union transducer used by the pipeline",
        "",
        "It recognizes every variant of every qualification through a shared "
        "prefix tree, so the whole catalog is normalized with one machine. "
        "Its full table is large; it is the union of the machines below, "
        "which are listed in full.",
        "",
        formal_definition_md(union, full_tables=False),
        "## One transducer per qualification",
        "",
    ]
    for canonical, spec in build_qualification_specs(catalog).items():
        variants = ", ".join(f"`{v}`" for v in catalog[canonical])
        parts.append(formal_definition_md(spec))
        parts.append(f"Variants recognized: {variants} → `{canonical}`")
        parts.append("")
    return "\n".join(parts)


def write_document(path=OUTPUT_PATH, catalog=None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(generate_document(catalog))
    return path


if __name__ == "__main__":
    print(f"Wrote {write_document()}")
